// The hands-on tutorial strip (first time only). T1..T7 are teaching triggers.
// Built in code so every row is exactly the same width.
function buildTutorial() {
  const W = 120, H = 20, g = [];
  for (let y = 0; y < H; y++) g.push(Array.from({ length: W }, (_, x) => (y === 0 || y >= 18 || x === 0 || x === W - 1 ? '#' : '.')));
  const put = (x, y, c) => { g[y][x] = c; };
  put(5, 16, 'P'); put(7, 16, '1');
  for (let y = 16; y <= 17; y++) for (let x = 20; x <= 21; x++) put(x, y, '#'); put(15, 16, '2');
  for (let x = 34; x <= 45; x++) put(x, 18, '^'); put(39, 11, 'o'); put(27, 16, '3');
  put(52, 16, '4'); put(57, 17, 'd');
  put(61, 16, '5'); for (let x = 66; x <= 71; x++) put(x, 18, '^');
  put(76, 16, '6'); for (let y = 10; y <= 17; y++) for (let x = 82; x <= 85; x++) put(x, y, '#'); put(80, 9, 'z');
  put(92, 16, '7'); put(105, 17, 'q'); put(114, 16, 'D');
  for (const x of [4, 22, 40, 58, 76, 94, 112]) put(x, 4, 'L');
  return g.map((r) => r.join(''));
}
